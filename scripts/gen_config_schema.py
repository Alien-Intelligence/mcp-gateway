"""Write the JSON Schema of the gateway configuration (docs/config.schema.v1.json) and embed it in
the Helm chart's values schema (charts/mcp-gateway/values.schema.json, ``properties.config``), so
that ``helm install`` refuses a configuration the gateway would refuse.

``python scripts/gen_config_schema.py`` rewrites the committed files; ``--check`` exits 1 when one
of them is not what the model produces. The unit test runs the same comparison. The rest of the
chart's values schema is written by hand: only ``$defs`` and ``properties.config`` are generated.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from mcp_gateway.config import CONFIG_VERSION, GatewayConfig

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "docs" / f"config.schema.v{CONFIG_VERSION}.json"
CHART_SCHEMA_PATH = ROOT / "charts" / "mcp-gateway" / "values.schema.json"


def render_schema() -> str:
    """The schema as the exact text of the committed file."""
    schema: dict[str, Any] = GatewayConfig.model_json_schema(mode="validation")
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": f"mcp-gateway configuration, version {CONFIG_VERSION}",
        **schema,
    }
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def render_chart_schema() -> str:
    """The chart's values schema as the exact text of the committed file.

    The gateway schema's definitions move to the root of the values schema, where its ``#/$defs/...``
    references resolve unchanged. ``config`` is validated only when set: an empty ``config`` means
    ``existingSecret`` carries the document, which the chart cannot read.
    """
    gateway: dict[str, Any] = json.loads(render_schema())
    definitions = gateway.pop("$defs")
    for key in ("$schema", "title"):
        del gateway[key]
    values: dict[str, Any] = json.loads(CHART_SCHEMA_PATH.read_text(encoding="utf-8"))
    values.pop("$defs", None)
    values["$defs"] = definitions
    values["properties"]["config"] = {
        "type": "object",
        "description": (
            "The MCP_GATEWAY_CONFIG document (docs/configuration.md), validated against "
            f"docs/config.schema.v{CONFIG_VERSION}.json when set. Generated by "
            "scripts/gen_config_schema.py."
        ),
        "if": {"minProperties": 1},
        "then": gateway,
    }
    return json.dumps(values, indent=2) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    outputs = {SCHEMA_PATH: render_schema(), CHART_SCHEMA_PATH: render_chart_schema()}
    if args.check:
        stale = [
            path
            for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(f"{path} is stale: run python scripts/gen_config_schema.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
